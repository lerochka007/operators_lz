#пользователь вводит число с клавиатуры 
n = int(input("Введите целое число"))
#проверяем, что число входит в заданный диапазон от 1 до 100 000
if 1 <= n <= 100000:
    #создаем переменную k для подсчета количества шагов
    k = 0
    #цикл выполняется до тех пор, пока n больше 0
    while n > 0:
        #каждый шаг мы вычитаем из числа 3
        n = n - 3
        #увеличиваем счетчик шагов k на 1
        k = k + 1
    #выводим итоговый результат на экран
    print(k)